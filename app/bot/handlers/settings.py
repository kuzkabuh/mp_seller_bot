"""
Версия файла: 1.1.0
Описание: Настройки/служебные обработчики для mp_seller_bot (fallback, обработка отмены, мягкая навигация).
Дата изменения: 2025-12-28

Этот модуль содержит fallback-обработчик и служебную обработку
неизвестных сообщений. Если ни один из зарегистрированных обработчиков
не сработал, бот отправит сообщение с подсказкой обратиться к меню или помощи.

Улучшения:
- Добавлена обработка "Отмена" и "Назад в меню" как универсальные команды навигации
  (если соответствующие обработчики не подключены в других модулях).
- Добавлены подсказки по безопасности при вводе токена (не присылать токен повторно в чат).
- Добавлены рекомендации по использованию меню (кнопки).
"""

from __future__ import annotations

from aiogram import F, Router
from aiogram.types import Message

from bot.keyboards.menu import (
    BTN_BACK_TO_MENU,
    BTN_CANCEL,
    BTN_HELP,
    main_menu,
)

router = Router()


@router.message(F.text == BTN_CANCEL)
async def cancel_action(message: Message) -> None:
    """
    Универсальная «Отмена».

    Примечание:
    Здесь мы не сбрасываем FSM-состояние, потому что FSM может быть не включен
    или управляться в других обработчиках. Сброс состояния корректнее делать
    в модуле, который использует FSM, чтобы не ломать сценарии.
    """
    await message.answer("Действие отменено. Возвращаю в главное меню.", reply_markup=main_menu())


@router.message(F.text == BTN_BACK_TO_MENU)
async def back_to_menu(message: Message) -> None:
    """
    Универсальный возврат в меню (на случай, если профильный обработчик не подключен).
    """
    await message.answer("Главное меню.", reply_markup=main_menu())


@router.message()
async def fallback(message: Message) -> None:
    """Отправляет сообщение по умолчанию, если команда/кнопка не распознана."""
    text = (
        "Не понял сообщение.\n\n"
        "Что можно сделать:\n"
        f"- Нажмите «{BTN_HELP}» для справки\n"
        "- Используйте кнопки меню ниже\n\n"
        "Важно:\n"
        "- Если вы вводили API-ключ/токен, не отправляйте его повторно в чат.\n"
        "  Для подключения используйте раздел «Подключения» и следуйте инструкциям бота."
    )
    await message.answer(text, reply_markup=main_menu())


